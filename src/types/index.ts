export type ThemePreference = 'light' | 'dark' | 'system';
export type SurfaceStyle = 'solid' | 'glass';
export type VoiceMode = 'raw' | 'light' | 'structured' | 'formal';
export type OutputLanguage = 'auto' | 'zh-CN' | 'en';
export type InsertStrategy = 'paste' | 'copy';

export interface ProviderSettings {
  preset: string;
  baseUrl: string;
  apiKey: string;
  model: string;
}

/** Result of a live probe. `models` is only meaningful for ASR. */
export interface ProviderTestResult {
  kind: 'asr' | 'polish';
  ok: boolean;
  models?: number | null;
}

export interface HotkeySettings {
  dictate: string;
  cancel: string;
  ask: string;
  /** Cycle through style packs without opening the app. */
  style: string;
}

/** A named mode + instruction combination. */
export interface StylePack {
  id: string;
  name: string;
  mode: VoiceMode;
  instruction: string;
  /** Built-ins are generated by the backend and cannot be edited or deleted. */
  builtin: boolean;
}

export interface VoiceSettings {
  mode: VoiceMode;
  outputLanguage: OutputLanguage;
  asr: ProviderSettings;
  polish: ProviderSettings;
  insert: InsertStrategy;
  contextChars: number;
  dictionaryEnabled: boolean;
  hotkeys: HotkeySettings;
  localAsr: LocalAsrSettings;
  /** Extra instruction appended to the polish prompt. */
  customInstruction: string;
  /** Packs authored by the user; built-ins are not stored here. */
  stylePacks: StylePack[];
  /** Id of the pack last applied, or an empty string. */
  activeStylePack: string;
  /** Packs the global style hotkey should skip; empty means cycle all. */
  excludedStylePacks: string[];
  /** Hold the dictate hotkey to talk instead of tapping it. */
  holdToTalk: boolean;
  /** Stop by itself when the speaker goes quiet. */
  autoStop: boolean;
  /** How much silence ends a recording, in milliseconds. */
  silenceMs: number;
  /** Show a provisional transcript while the user is still speaking. */
  livePreview: boolean;
  /** Short blips when the microphone opens and closes. */
  soundFeedback: boolean;
}

export interface GeneralSettings {
  language: string;
  onboarded: boolean;
}

export interface UiSettings {
  theme: ThemePreference;
  /** Visual treatment of panels: flat solid cards or Liquid Glass. */
  surface: SurfaceStyle;
  compact: boolean;
  pageSize: number;
}

export interface AppSettings {
  general: GeneralSettings;
  ui: UiSettings;
  voice: VoiceSettings;
}

export interface SettingsResponse {
  success: boolean;
  settings: AppSettings;
}

export interface PlatformFeatures {
  globalHotkey: boolean;
  autostart: boolean;
  syntheticPaste: boolean;
  localAsr: boolean;
  floatingCapsule: boolean;
}

export type SecretBackend = 'keychain' | 'file';

export interface AppInfo {
  name: string;
  version: string;
  platform: string;
  family: string;
  isMobile: boolean;
  /** Where API keys are actually stored on this machine. */
  secrets: SecretBackend;
  features: PlatformFeatures;
}

export interface DictionaryEntry {
  id: string;
  term: string;
  aliases: string[];
  note: string;
  enabled: boolean;
  hits: number;
  createdAt: string;
  updatedAt: string;
}

export interface DictionaryInput {
  term: string;
  aliases: string[];
  note: string;
  enabled: boolean;
}

export interface Snippet {
  id: string;
  /** What the speaker says. */
  trigger: string;
  /** What lands in the document, line breaks included. */
  expansion: string;
  note: string;
  enabled: boolean;
  hits: number;
  createdAt: string;
  updatedAt: string;
}

export interface SnippetInput {
  trigger: string;
  expansion: string;
  note: string;
  enabled: boolean;
}

export interface HistoryEntry {
  id: string;
  createdAt: string;
  raw: string;
  text: string;
  mode: VoiceMode;
  asrModel: string;
  polishModel: string;
  durationMs: number;
  asrMs: number;
  polishMs: number;
  chars: number;
  app: string;
  inserted: boolean;
  copied: boolean;
  /** The user fixed this text by hand in history. */
  edited: boolean;
}

export interface DayStat {
  date: string;
  count: number;
  chars: number;
}

export interface Stats {
  todayCount: number;
  todayChars: number;
  todaySeconds: number;
  totalCount: number;
  avgAsrMs: number;
  avgPolishMs: number;
  savedMinutes: number;
  streakDays: number;
  /** Characters per minute of speech, today. */
  charsPerMin: number;
  /** Last 14 days, oldest first. */
  days: DayStat[];
}

export interface HotkeyFailure {
  accelerator: string;
  reason: string;
}

export interface HotkeyStatus {
  supported: boolean;
  registered: string[];
  failed: HotkeyFailure[];
}

export interface InsertOutcome {
  inserted: boolean;
  copied: boolean;
  reason: string | null;
}

export interface DictationResult {
  entry: HistoryEntry;
  text: string;
  raw: string;
  insert: InsertOutcome;
}

/** A take that failed after recording; the audio is still in memory. */
export interface PendingDictation {
  error: string;
  createdAt: string;
  durationMs: number;
  app: string;
}

/** Result of rewriting or translating the current selection. */
export interface SelectionOutcome {
  before: string;
  after: string;
  inserted: boolean;
  reason?: string | null;
}

export interface LocalAsrSettings {
  enabled: boolean;
  baseUrl: string;
  model: string;
  modelDir: string;
}

export interface DictationRequest {
  audioBase64: string;
  mime: string;
  durationMs: number;
  /** Milliseconds of actual voice in the recording, measured client-side. */
  voicedMs?: number;
  app?: string;
  context?: string;
  outputLanguage?: OutputLanguage;
}

export type AppView = 'dashboard' | 'history' | 'dictionary' | 'providers' | 'packs' | 'settings';
