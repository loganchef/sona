import { useCallback, useEffect, useMemo, useRef, useState, type ReactNode } from 'react';
import { useTranslation } from 'react-i18next';
import { TopBar } from '@/components/layout/TopBar';
import { MobileTopBar } from '@/components/layout/MobileTopBar';
import { MobileBottomNav } from '@/components/layout/MobileBottomNav';
import { AmbientBackground } from '@/components/theme/AmbientBackground';
import { GlassFilters } from '@/components/theme/GlassFilters';
import { Dashboard } from '@/components/views/Dashboard';
import { HistoryView } from '@/components/views/HistoryView';
import { DictionaryView } from '@/components/views/DictionaryView';
import { ProvidersView } from '@/components/views/ProvidersView';
import { StylePacksView } from '@/components/views/StylePacksView';
import { SettingsView } from '@/components/views/SettingsView';
import { SetupWizard } from '@/components/setup/SetupWizard';
import { Toast, type ToastMessage, type ToastType } from '@/components/common/Toast';
import { SurfaceProvider } from '@/components/theme/SurfaceContext';
import { useSettings } from '@/hooks/useSettings';
import { useHistory } from '@/hooks/useHistory';
import { useDictionary } from '@/hooks/useDictionary';
import { useSnippets } from '@/hooks/useSnippets';
import { useTheme } from '@/hooks/useTheme';
import { useMobile } from '@/hooks/useMobile';
import { api, isTauri } from '@/api';
import i18n, { normalizeLanguage } from '@/i18n';
import type {
  AppInfo,
  AppSettings,
  AppView,
  StylePack,
  ThemePreference,
  VoiceSettings,
} from '@/types';

const VIEW_STORAGE_KEY = 'sona.view';
const VIEWS: AppView[] = ['dashboard', 'history', 'dictionary', 'providers', 'packs', 'settings'];

function readForceSetup(): boolean {
  try {
    return new URLSearchParams(window.location.search).get('setup') === '1';
  } catch {
    return false;
  }
}

function readInitialView(): AppView {
  // Deep links (`?view=history`) make every screen reachable without clicking,
  // which the screenshot checks and the docs rely on.
  try {
    const requested = new URLSearchParams(window.location.search).get('view');
    if (requested && (VIEWS as string[]).includes(requested)) return requested as AppView;
  } catch {
    // Ignore malformed URLs.
  }

  try {
    const stored = localStorage.getItem(VIEW_STORAGE_KEY);
    if (stored && (VIEWS as string[]).includes(stored)) return stored as AppView;
  } catch {
    // Ignore storage errors.
  }
  return 'dashboard';
}

export default function App() {
  const { t } = useTranslation();
  const { isMobile } = useMobile();
  const {
    settings,
    loading: settingsLoading,
    error: settingsError,
    updateSetting,
    resetSettings,
    reload,
    applyStylePack,
  } = useSettings();
  const history = useHistory();
  const dictionary = useDictionary();
  const snippets = useSnippets();

  const [view, setView] = useState<AppView>(readInitialView);
  const [setupOpen, setSetupOpen] = useState(readForceSetup);
  const [appInfo, setAppInfo] = useState<AppInfo | null>(null);
  const [builtinPacks, setBuiltinPacks] = useState<StylePack[]>([]);
  const [toast, setToast] = useState<ToastMessage | null>(null);
  const toastId = useRef(0);

  useTheme(settings?.ui.theme);

  // The menu-bar item navigates the window it just revealed.
  useEffect(() => {
    if (!isTauri()) return;
    let unlisten: (() => void) | undefined;
    let cancelled = false;

    void import('@tauri-apps/api/event').then(async ({ listen }) => {
      const fn = await listen<{ action: string }>('sona://tray', (event) => {
        const target = event.payload.action;
        if (target === 'history') setView('history');
        else if (target === 'settings') setView('settings');
        else if (target === 'open') setView('dashboard');
      });
      if (cancelled) fn();
      else unlisten = fn;
    });

    return () => {
      cancelled = true;
      unlisten?.();
    };
  }, []);

  const notify = useCallback((message: string, type: ToastType = 'success') => {
    toastId.current += 1;
    setToast({ id: toastId.current, message, type });
  }, []);

  const closeToast = useCallback(() => setToast(null), []);

  useEffect(() => {
    try {
      localStorage.setItem(VIEW_STORAGE_KEY, view);
    } catch {
      // Ignore storage errors.
    }
  }, [view]);

  useEffect(() => {
    let cancelled = false;
    api.app
      .info()
      .then((info) => {
        if (!cancelled) setAppInfo(info);
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, []);

  // Built-ins are generated by Rust and follow the UI language, so the
  // Dashboard and Settings need a fresh copy when the language changes.
  useEffect(() => {
    if (!settings) return;
    let cancelled = false;
    api.packs
      .list()
      .then((packs) => {
        if (!cancelled) setBuiltinPacks(packs.filter((pack) => pack.builtin));
      })
      .catch(() => undefined);
    return () => {
      cancelled = true;
    };
  }, [settings?.general.language]);

  const activePack = useMemo(() => {
    if (!settings?.voice.activeStylePack) return null;
    const custom = settings.voice.stylePacks.map((pack) => ({ ...pack, builtin: false }));
    return (
      [...builtinPacks, ...custom].find(
        (pack) => pack.id === settings.voice.activeStylePack,
      ) ?? null
    );
  }, [builtinPacks, settings]);

  // The style hotkey runs in the Rust process; reload so the main window and
  // the capsule agree on the active mode without a manual refresh.
  useEffect(() => {
    if (!isTauri()) return;
    let unlisten: (() => void) | undefined;
    let unlistenError: (() => void) | undefined;
    let cancelled = false;

    void import('@tauri-apps/api/event').then(async ({ listen }) => {
      const onPack = await listen<{ name: string }>('sona://style-pack', (event) => {
        void reload();
        notify(t('packs.applied', { name: event.payload.name }), 'success');
      });
      const onError = await listen<{ reason: string }>('sona://style-pack-error', (event) => {
        notify(
          event.payload.reason === 'style_pack_not_found'
            ? t('packs.notFound')
            : event.payload.reason,
          'error',
        );
      });
      if (cancelled) {
        onPack();
        onError();
      } else {
        unlisten = onPack;
        unlistenError = onError;
      }
    });

    return () => {
      cancelled = true;
      unlisten?.();
      unlistenError?.();
    };
  }, [notify, reload, t]);

  useEffect(() => {
    if (!settings) return;
    const language = normalizeLanguage(settings.general.language);
    if (i18n.resolvedLanguage !== language) {
      void i18n.changeLanguage(language);
    }
  }, [settings]);

  const navigate = useCallback((next: AppView) => setView(next), []);

  const changeSettings = useCallback(
    async <K extends keyof AppSettings>(key: K, value: AppSettings[K]) => {
      const next = await updateSetting(key, value);
      return next;
    },
    [updateSetting],
  );

  const saveVoice = useCallback(
    async (voice: VoiceSettings) => {
      await updateSetting('voice', voice);
    },
    [updateSetting],
  );

  const handleReset = useCallback(async () => {
    const next = await resetSettings();
    notify(t('toast.settingsReset'));
    return next;
  }, [notify, resetSettings, t]);

  const finishSetup = useCallback(async () => {
    if (!settings) return;
    await updateSetting('general', { ...settings.general, onboarded: true });
    setSetupOpen(false);
    // Drop the `?setup=1` deep link so a reload does not reopen the guide.
    try {
      const url = new URL(window.location.href);
      if (url.searchParams.has('setup')) {
        url.searchParams.delete('setup');
        window.history.replaceState({}, '', url);
      }
    } catch {
      // History is best-effort; the flag is already saved.
    }
    notify(t('setup.finished'), 'success');
  }, [notify, settings, t, updateSetting]);

  const changeTheme = useCallback(
    (theme: ThemePreference) => {
      if (!settings) return;
      void updateSetting('ui', { ...settings.ui, theme }).catch((cause) => {
        notify(cause instanceof Error ? cause.message : String(cause), 'error');
      });
    },
    [notify, settings, updateSetting],
  );

  if (settingsLoading && !settings) {
    return <SplashScreen label={t('app.loading')} />;
  }

  if (!settings) {
    return (
      <SplashScreen
        label={settingsError ?? t('app.loadError')}
        action={
          <button type="button" className="btn-primary" onClick={() => void reload()}>
            {t('common.retry')}
          </button>
        }
      />
    );
  }

  const surface = settings.ui.surface;

  if (setupOpen || !settings.general.onboarded) {
    return (
      <SurfaceProvider surface={surface}>
        <div data-surface={surface} className="relative min-h-dvh overflow-y-auto">
          <GlassFilters />
          <AmbientBackground />
          <SetupWizard
            settings={settings}
            appInfo={appInfo}
            onUpdate={changeSettings}
            onFinish={finishSetup}
            onNotify={notify}
          />
          <Toast toast={toast} onClose={closeToast} />
        </div>
      </SurfaceProvider>
    );
  }

  return (
    <SurfaceProvider surface={surface}>
      <div data-surface={surface} className="relative flex h-dvh flex-col overflow-hidden">
        <GlassFilters />
        <AmbientBackground />

        {isMobile ? (
          <MobileTopBar theme={settings.ui.theme} onThemeChange={changeTheme} />
        ) : (
          <TopBar view={view} onNavigate={navigate} theme={settings.ui.theme} onThemeChange={changeTheme} />
        )}

        <main className="min-h-0 flex-1 overflow-hidden">
          {view === 'dashboard' && (
            <Dashboard
              settings={settings}
              appInfo={appInfo}
              activePack={activePack}
              stats={history.stats}
              entries={history.entries}
              onNavigate={navigate}
              onNotify={notify}
              onRecorded={() => void history.reload()}
              onOpenSetup={() => setSetupOpen(true)}
            />
          )}

          {view === 'history' && (
            <HistoryView
              entries={history.entries}
              loading={history.loading}
              error={history.error}
              onUpdate={history.update}
              onDelete={history.remove}
              onClear={history.clear}
              onNotify={notify}
            />
          )}

          {view === 'dictionary' && (
            <DictionaryView
              entries={dictionary.entries}
              loading={dictionary.loading}
              snippets={snippets.snippets}
              snippetsLoading={snippets.loading}
              onSave={dictionary.save}
              onRemove={dictionary.remove}
              onSaveSnippet={snippets.save}
              onRemoveSnippet={snippets.remove}
              onNotify={notify}
            />
          )}

          {view === 'providers' && (
            <ProvidersView
              voice={settings.voice}
              secretBackend={appInfo?.secrets}
              onSave={saveVoice}
              onNotify={notify}
            />
          )}

          {view === 'packs' && (
            <StylePacksView
              settings={settings}
              onUpdate={changeSettings}
              onApply={applyStylePack}
              onNotify={notify}
            />
          )}

          {view === 'settings' && (
            <SettingsView
              settings={settings}
              appInfo={appInfo}
              activePack={activePack}
              onUpdate={changeSettings}
              onReset={handleReset}
              onNotify={notify}
              onRestartSetup={() => setSetupOpen(true)}
              onNavigate={navigate}
            />
          )}
        </main>

        {isMobile && <MobileBottomNav view={view} onNavigate={navigate} />}

        <Toast toast={toast} onClose={closeToast} />
      </div>
    </SurfaceProvider>
  );
}

interface SplashScreenProps {
  label: string;
  action?: ReactNode;
}

function SplashScreen({ label, action }: SplashScreenProps) {
  return (
    <div className="relative flex h-dvh flex-col items-center justify-center gap-4 px-6 text-center">
      <AmbientBackground />
      <img src="/logo.svg" alt="" className="h-16 w-16 rounded-2xl shadow-lg" />
      <div className="flex items-center gap-2 text-sm font-medium text-slate-600 dark:text-slate-400">
        {!action && (
          <span className="h-4 w-4 animate-spin rounded-full border-2 border-brand-500 border-t-transparent" />
        )}
        <span>{label}</span>
      </div>
      {action}
    </div>
  );
}
